function halfUndeadTraits(prefix: string): FeatureDefinition[] {
  const f = (key: string, name: string, description: string, category: FeatureDefinition["category"]): FeatureDefinition => ({
    key: `${prefix}-${key}`,
    name,
    description,
    category,
    source: DM313,
    sourceUrl: DM313_PATH,
  });
  return [
    f("call-of-undeath", "Call of Undeath (Ex)", "There is a 3% chance per Hit Die that, upon the half-undead's death, it rises as a full undead creature of its undead progenitor's kind.", "special-quality"),
    f("darkvision", "Darkvision (Ex)", "Darkvision with a range of 60 feet. If the base creature already had darkvision, use the greater range.", "special-quality"),
    f("detection", "Detection (Ex)", "The half-undead registers as an undead creature for the purposes of spells and effects that detect undead (such as detect undead). It counts as half its Hit Dice for the purposes of aura strength.", "special-quality"),
    f("fortification", "Fortification (Ex)", "When a critical hit or sneak attack is scored on the half-undead, there is a 50% chance that the critical hit or sneak attack is negated and damage is rolled normally. If the half-undead wears magic armor with any form of the fortification quality, use the better percentage.", "special-quality"),
    f("immunity-to-energy-drain", "Immunity to Energy Drain (Ex)", "The half-undead is immune to energy drain attacks.", "special-quality"),
    f("necrotic-life", "Necrotic Life (Ex)", "Even on a failed save, the half-undead takes only half hit point damage from spells and effects that deal damage through negative energy (such as inflict spells); on a successful save, it takes no damage.", "special-quality"),
    f("slow-aging", "Slow Aging (Ex)", "Upon reaching maturity, the half-undead ages at one-fourth of the base creature's normal rate.", "trait"),
    f("turn-kind", "Turn Kind (Ex)", "A half-undead cleric gains a +2 bonus on checks made to turn, rebuke, command, or bolster undead creatures of its ancestral kind.", "special-quality"),
    f("vulnerability-to-holy-water", "Vulnerability to Holy Water (Ex)", "Holy water scalds the half-undead's flesh, dealing 1d4 points of damage per direct hit with a flask.", "special-quality"),
    f("vulnerability-to-turning", "Vulnerability to Turning (Ex)", "A turning attempt that would turn or rebuke an undead of the half-undead's Hit Dice imposes a −4 penalty on its attacks, saves, skill checks, and ability checks for 10 rounds or until the turning creature attacks it. A turning attempt that would destroy or command an undead of its Hit Dice instead stuns the half-undead for 2d4 rounds.", "special-quality"),
    f("saves", "Half-Undead Saves", "+2 racial bonus on saving throws against fear, poison, disease, paralysis, and spells from the necromancy school.", "trait"),
  ];
}

