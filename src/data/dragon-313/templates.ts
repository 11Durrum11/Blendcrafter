import type { TemplateDefinition, FeatureDefinition } from "@/engine/types";

// STAGING DRAFT — Dragon Magazine #313 pack (library-staging/packs/dragon-magazine/issue-313)
// The issue's seventeen templates, from four articles:
//   * "Born of Death" (by Trent Troop, pp. 60–66): the four
//     half-undead — fetch (half-ghost), gheden (half-zombie), ghul
//     (half-ghoul), katane (half-vampire). All four carry the shared
//     Half-Undead Traits sidebar (pp. 60–61) in full; the catalog has
//     no shared-template mechanism, so the sidebar's eleven traits
//     are written into each record via the halfUndeadTraits() helper
//     below.
//   * "Dragon Psychoses" (by Steven Palmer Peterson, pp. 78–83):
//     five acquired templates for true dragons — nameless, ravening,
//     riddled, spellhoarding, wandering. Each record describes the
//     MOST ADVANCED form, per the article's severity sidebar (see
//     reference.md).
//   * "Faiths of Faerûn: Elder Serpents of Set": the elder serpent.
//   * "Strange Bedfellows" (pp. 92–96): seven half-monster templates
//     — half-doppelganger, half-jann, half-minotaur, half-nymph,
//     half-ogre, half-rakshasa, half-satyr.
// Transcribed from the magazine text on archive.org
// (DragonMagazine313_djvu.txt), cross-checked against the
// realmshelps.net transcriptions of the Born of Death article and
// the elder serpent template. Descriptions are faithful mechanical
// paraphrases in our own words; no magazine prose is reproduced.
//
// APOC note: Shaun's undead house rules (maximized hit points, +4
// turn/control resistance, re-rolling each round) are campaign
// adjustments applied on top at the table — they are NOT baked into
// the half-undead records, which carry the printed Vulnerability to
// Turning exactly as published. See SCREENING.md.
//
// Judgment calls flagged in MANIFEST.md include: the -313 id
// suffixes (fetch-313 vs the unrelated Green Ronin fetch race;
// half-doppelganger-313 and half-rakshasa-313 vs the Bastards &
// Bloodlines printings; half-ogre-313 vs the Races of Destiny race);
// the conditional CR/LA values recorded as single numbers with the
// full printed rule in each summary (nameless, half-minotaur,
// half-ogre); the elder serpent's dice-based ability increases
// (Intelligence set to 2d6+6; Wisdom and Charisma +2d4+4), which
// abilityModifiers cannot express and which therefore ride in a
// feature; and the gheden's CR +0, which rests on the article's
// sample creature (no CR line is printed in its template block).

