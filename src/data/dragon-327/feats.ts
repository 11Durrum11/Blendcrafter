// Dragon Magazine #327 (January 2005) — feat draft: 7 feats.
// "Silicon Sorcery: Champions of Norrath" (James Jacobs), pp. 70-71 — the article's one
// worked example of its "racial feat tree" framework: the dark elf (drow) tree. Every
// feat is printed with the type tag [Racial-Drow]; the feat category union has a
// "race-specific" value, so they stage as category "race-specific" with "Drow" carried
// as the first prerequisite (the tag is the printed race gate), the article's framework
// rules (racial feats cannot be taken as class bonus feats; a character may possess at
// most eight racial feats) carried in the shared RACIAL_TREE_SPECIAL text, and each
// feat's own printed Special line appended where it differs. The program survey
// estimated ~5 feats; the article prints seven (see MANIFEST). All seven were verified
// against rendered page images (p. 71).
// ⚠️ APOC FLAG — see SCREENING.md: these are drow racial feats. In APOC the drow CHOSE
// the demons, and the catalog's drow races are APOC-grayed. The feats stage as printed;
// their disposition is Shaun's call at screening. Not decided here.

import type { FeatDefinition } from "@/engine/types";

const SRC = "Dragon Magazine #327 — Silicon Sorcery: Champions of Norrath (James Jacobs), pp. 70-71";
const SRC_URL = "https://archive.org/details/DragonMagazine260_201801";

const RACIAL_TREE_SPECIAL =
  "Racial feats represent the strengths and virtues of your chosen race. You cannot select a racial feat as a bonus feat gained from a class feature (such as a fighter's bonus feats) or any other source; thus, at 20th level, a character may possess a maximum of eight racial feats. Many racial feats grant supernatural abilities: while the feat itself is not supernatural, the effect generated by it is, and thus may be suppressed with antimagic.";

type FeatSeed = Partial<FeatDefinition> & Pick<FeatDefinition, "id" | "name" | "benefitSummary">;

function F(seed: FeatSeed): FeatDefinition {
  return {
    category: "race-specific",
    prerequisites: ["Drow"],
    source: SRC,
    sourceUrl: SRC_URL,
    ruleset: "core",
    ...seed,
  } as FeatDefinition;
}

