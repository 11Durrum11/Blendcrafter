// Spelljammer ships and gear, converted from AD&D 2e to 3.5
// Ships carry category "spelljamming
// ship" so they group together in Equipment and on the
// Spelljamming page. Source: Shaun's own copy of Spelljammer:
// Adventures in Space (Lorebook of the Void ship chapters),
// read page by page from his scan. (The Ships in Space book
// in the same folder is artwork only and is not a source.)
// House style: short mechanical summaries written for this
// dataset; the book's text is not reproduced.
//
// Ship stat blocks are carried over as printed: Tonnage,
// Hull Points (treat as the vessel's hit points), Crew
// (minimum/maximum), Maneuver Class (letter grade, A best),
// Landing, Armor Rating, Saves As (hull material), Power
// Type, Ship's Rating, Standard Armament, Cargo, Keel/Beam.
// ARMOR RATING is the 2e descending scale — lower is better
// protected, 0 the best printed; do not read it as a 3.5 AC.
// The Lorebook prints no ship prices; every price here was
// verified against the boxed set's own Concordance of
// Arcane Space, ch. 8 "Ships of Wildspace" price list, and
// the Concordance notes the listed crew/armament figures are
// capacities the hull supports, not gear included in the
// purchase price. Three hulls have no price in either book:
// the Neogi Mindspider (a new, secret class), the Elven
// Armada (never sold), and The Spelljammer (unique).

