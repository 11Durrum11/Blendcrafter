// Complete Psionic (WotC, 2006) — Chapter 4: Powers, Mantles, and
// Items. The book's NEW powers (printed pp. 78-104), modeled as
// spells — the same treatment Magic of Incarnum's soulmelds got —
// because the builder files powers alongside spells. (Powers that
// appear only in this book's class and mantle lists without a
// description here are Expanded Psionics Handbook powers and live
// with that book.)
//
// Conventions, following the soulmeld pack: the printed Level line
// is transcribed verbatim into the `levels` map — its keys are the
// book's own list names: classes ("Psion/Wilder", "Psychic
// Warrior", "Ardent", "Divine Mind", "Lurk"), psion disciplines
// ("Seer", "Shaper", "Kineticist", "Egoist", "Nomad", "Telepath"),
// and ardent/divine mind mantles ("Physical Power", "Pain and
// Suffering", "Magic", "Time", ...). The discipline line is the
// `school`; parenthetical subschools and bracketed descriptors on
// that line are folded into `descriptors`. The Display line is
// carried in `components`, Manifesting Time in `castingTime`, and
// Power Resistance in `spellResistance` (a stat block with no
// Saving Throw line is recorded as "None", no Power Resistance
// line as "No"). Each summary opens with the power point cost and
// closes with the power's full Augment text.
//
// A handful of entries print abbreviated stat blocks (Fiendish
// Conduit; Protection from Good, Psionic) — discipline and Level
// only, the rest functioning as a cross-referenced power; the
// unprinted fields read "See text".
//
// Canon note (Shaun's ruling): his campaign uses psionics-magic
// transparency, so these powers interact with spells exactly as
// printed; nothing here walls psionics off from magic. The Magic
// mantle's granted ability is that same transparency rule.
//
// Transcribed from page images of Shaun's own copy (this PDF's
// text layer is empty), 2026-11-05. Summaries are mechanical
// paraphrases in our own words; no book prose is reproduced.

