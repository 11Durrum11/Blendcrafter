// omni-swept precedent for alchemical items); [Magical]
// entries are in magic-items.ts. The book prints no weights,
// so weight is "—" throughout. For catalog entries, "cost" is
// the book's Market Price exactly as printed; each entry's
// notes carry its classification, Caster Level, creation DC,
// prerequisites, and Cost to Create in our own words. Herb
// notes carry the printed stat block (Rarity / Environment /
// Harvest / Game Use). The book is 3.0-era ("subdual damage",
// Wilderness Lore); effects are transcribed as printed.
// Like the other omni-swept third-party books, records carry
// ruleset "core".
//
// Printing quirks recorded as printed: Breeam's cost line is
// truncated mid-phrase in the book ("1 gp/" with no unit);
// Silentscent Powder's DC prints as "#17"; Holly's cost shows
// a stray glyph ("5 7sp") and is read as 5 sp; Mistletoe's
// Environment prints as the unexplained abbreviation "MPD".
// Name variants between the treasure tables (pp. 53-59) and
// the entries are noted in the extraction report; entry names
// govern.

