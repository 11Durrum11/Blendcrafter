const DOC4 = "Misc Other House Rules (house-rules doc #4)";
const DOC4_URL = "workspace/user/files/4._MISC_OTHER_HOUSE_RULES_6_xpih.docx";

export interface HouseRuleEntry {
  id: string;
  name: string;
  /** The section of Shaun's document the entry belongs to. */
  section: string;
  ruleset: Ruleset;
  /** Faithful condensation of Shaun's text. */
  summary: string;
  source: string;
  sourceUrl: string;
}

export interface SummoningSpellEntry {
  id: string;
  /** Spell name exactly as written in Shaun's table. */
  name: string;
  /** The table's Allowed column: yes = the spell may be cast (under the rework). */
  allowed: boolean;
  /** The table's "*" marker: post-apocalyptic terrestrial teleport BAD JU-JU. */
  badJuJu: boolean;
  /** Book exactly as written in Shaun's table. */
  book: string;
  /** The table's Type column, exactly as written. */
  bookType: string;
  /** True when a spell record of this name exists in the builder. */
  inBuilder: boolean;
  /** The matching spell record's id, when inBuilder. */
  spellId?: string;
  ruleset: Ruleset;
  source: string;
  sourceUrl: string;
}

function rule(section: string, id: string, name: string, summary: string): HouseRuleEntry {
  return { id, name, section, ruleset: "homebrew", summary, source: DOC4, sourceUrl: DOC4_URL };
}

