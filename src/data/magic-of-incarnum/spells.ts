// Magic of Incarnum (WotC, 2005). Two kinds of records live
// in this file:
//
// (1) SOULMELDS (Chapter 4, printed pp. 54-94), modeled as
// spells per the build brief: one record per soulmeld, with
// school "Incarnum (soulmeld)". Soulmelds have no spell
// level — the `levels` map names each meldshaping class
// whose list includes the meld, at level 1 as a placeholder,
// and the meld's chakra placement is carried in
// targetOrArea ("Chakra: ..."). The printed stat block
// (Descriptors / Classes / Chakra / Saving Throw) is
// transcribed into descriptors / levels / targetOrArea /
// savingThrow. Summaries compress, in order: the base
// effect, the "Essentia:" investment scaling, and each
// "Chakra Bind" effect. Shaping is not casting: soulmelds
// are shaped during 1 hour of meditation after rest, last
// until unshaped, and are supernatural (spell resistance
// does not apply). Where the printed Classes line lists a
// meld for a class but a class table (Tables 4-1 to 4-3)
// places it on a different chakra, the description's
// Chakra line governs.
//
// (2) The book's actual new spells (Chapter 5, printed
// pp. 98-107), transcribed as ordinary spell records.
// Spells with the incarnum descriptor require the Incarnum
// Spellshaping feat to cast, as printed; spells whose
// components line carries (E) accept essentia investment
// when cast.
//
// Transcribed from the pdftotext extraction of Shaun's own
// copy, 2026-11-05. Summaries are short mechanical
// paraphrases in our own words; no book prose is reproduced.

