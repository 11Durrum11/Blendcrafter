// verified against a rendered page because the text
// layer scrambles its cost and weight columns, and the
// adventuring kit tables (p. 43) were likewise read from
// a rendered page (each kit's printed total was checked
// against the sum of its lines).
//
// Contents: 24 mundane dungeon gear items from Table
// 2-1 (each drill and hacksaw material is its own table
// row and its own record); the 4 weapon and armor
// modifications; the 8 alchemical items; and the 5
// premade adventuring kits, each a single record at its
// printed total cost and weight with the full contents
// in its notes (the book instructs players to write the
// kit's total cost and weight on the character sheet).
//
// The catalog has no modification record type, so the
// modifications follow the Heroes of High Favor
// masterwork-component precedent: equipment records
// with a "(Modification)" name qualifier, category
// "gear", and the modification's price modifier as the
// cost. Alchemical items carry category "alchemical
// gear", which is how the catalog files its Alchemical
// Gear section. Notes are short mechanical paraphrases
// in our own words; no book prose is reproduced.
//
// One price discrepancy is transcribed as printed in
// both places: Table 2-1 prices a greater lava stone at
// 144 gp, while the item text (p. 36) prices it at
// 114 gp. Following the Planar Handbook pack's handling
// of the same kind of conflict, the record's cost field
// follows the table (144 gp) and the text price is noted
// in the record.

