// Heroes of High Favor: Dwarves (Bad Axe Games, 2002) —
// Chapter 2 feats, fighting styles, and dwarven rune feats,
// printed pp. 3-10, transcribed from Shaun's own scanned copy
// (image-only; read visually page by page, 2026-11-04). This
// is a 3.0-era book: entries are transcribed as printed,
// including 3.0 forms such as the Expertise and Ambidexterity
// feats, the Scry/Intuit Direction skills, and move-equivalent
// actions (flagged in the draft report, not modernized).
//
// The book's bracketed designators are suggestions for who
// may take a feat, not extra prerequisites: [General, Fighter]
// feats are filed as "combat", [General, Dwarf] feats as
// "race-specific", and plain [General] feats as "general".
// Prerequisites arrays carry only the printed Prerequisites
// lines.
//
// Fighting styles (pp. 7-8) are not feats: a character gains
// a style's basic benefit automatically once its prerequisites
// are met. Each style is filed as one feat record whose
// benefit is the style benefit and whose "special" carries
// the acquisition rule and the Style Specialization benefit
// (a 4+ level fighter who already qualifies may spend a feat
// — style specializations count as fighter bonus feats — to
// gain it).
//
// The ten rune feats (pp. 8-10) share one rules block, printed
// pp. 8-9: each feat lets a dwarf identify, activate, and
// craft one rune. The shared block is repeated in each rune
// feat's "special" so every record stands alone in the app.
// Summaries are short mechanical paraphrases in our own
// words; no book prose is reproduced.

