// 2026-11-05. All nine prestige classes in the chapter
// are here.
// Printing quirks are recorded as printed, not silently
// resolved:
// - The chapter's table numbering is erratic (the
//   planomancer's table is numbered 4-7, the plane
//   singer's table 4-9 while its Sing Gate DC table is
//   4-8); table numbers are noted in the sources.
// - The epic cosmosopher sidebar's bonus-feats line
//   says "the astral reaver" — a misprint for
//   cosmosopher, flagged in that feature.
// - The planomancer's table lists an "Accuracy" special
//   at 6th level, but no Accuracy feature text appears
//   anywhere in the class entry; it is recorded as a
//   table-only feature saying so.
// - The energist's Table 4-3 prints ONLY class level
//   and specials for its 7 levels — no base attack
//   bonus or saving throw columns at all (verified at
//   250 DPI). Its progression rows therefore carry
//   zeros, its babProgression is a placeholder "half",
//   and its goodSaves list is empty: those numbers are
//   NOT book data, and the class's first feature says
//   so plainly for integration to adjudicate.
// - The ethereal pilot's requirements print the feat
//   "Awaken Ancestor" (the feat is Awaken Ancestry).
// - The warrior maiden's spells-or-bonus-feat text
//   example garbles its own 2nd/5th/8th-level schedule;
//   the feature records the schedule, not the example.
// Summaries are short mechanical paraphrases in our own
// words; no book prose is reproduced.

