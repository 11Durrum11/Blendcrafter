// the damage cannot be prevented by any means, but may
// be repaired normally) — those costs are carried in
// each summary. Where Table 3-1 and a feat's own text
// state a prerequisite differently (Feed, Maul, Thin
// Blood, Focus Cone), the record follows the feat's own
// text and the draft report flags the difference.
