// or weight is given anywhere in the book — so it is not
// built as a record (see the draft report).
//
// Runecannon general rules (p. 42) apply to every
// runecannon except the stationary runecannon: firing
// does not cause an attack of opportunity; a loaded
// runecannon may be fired as an attack of opportunity;
// loading does cause an attack of opportunity; the sound
// of firing can be heard up to a half-mile underground or
// a mile on the surface; runecannons cannot fire
// underwater, though they may fire while wet; they
// require regular maintenance (a cannoneer's kit and
// daily cleaning; each missed day gives every shot a 20%
// chance to foul in the barrel, ruining the round and
// causing 1d4 hit points of damage to the wielder); all
// runecannons are exotic weapons, but the Exotic Weapon
// Proficiency feat need be taken only once to cover all
// runecannons; firing requires a full-attack action, and
// the attacker is still allowed only one attack with the
// weapon. A damaged runecannon may not be fired until
// repaired (field repair with a cannoneer's toolkit:
// Craft (runecannon) check DC 25, 1d4 hours). A wielder
// may make one adjustment to a runecannon as a full-round
// action (p. 43): Accuracy (Craft (runecannon) DC 15, +1
// bonus to all attack rolls, cannot then fire beyond
// medium range; not for offhand runecannons), Damage
// (Craft (runecannon) DC 15, +1d4 damage on a successful
// attack but -1 circumstance penalty to all attacks; not
// with spike or fire ammunition — attempts jam the
// weapon), or Range (Craft (runecannon) DC 20, range
// increment doubled; ball and poison ammunition only, not
// for defender or stationary runecannons). No more than
// one adjustment at a time. The ammunition used for a
// given attack determines the runecannon's damage,
// critical range, range increment, and damage type; the
// Range Increment column of the Weapons Table gives each
// runecannon's modifier to the ammunition's increment.

