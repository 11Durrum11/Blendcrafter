//   * Birthright (p. 74): Bloodline and the seven [Blood] feats.
// Transcribed from the magazine text on archive.org
// (DragonMagazine315_djvu.txt). Benefit summaries are short
// mechanical paraphrases in our own words; no magazine prose is
// reproduced.
//
// Category notes (catalog FeatCategory union: general, item-creation,
// metamagic, race-specific, setting-specific, combat):
//   * Feats printed [Metamagic] (Clawed Spell, Piercing Spell) ship
//     as "metamagic" (the issue-314 Radiant Spell convention).
//   * Feats whose printed Special line makes them fighter bonus
//     feats ship as "combat" (the catalog's Ghostwalk convention —
//     Saddleback, Twin Sword Style): Companion Guard Style,
//     Giantkiller, Jungle Fighter, Mountain Fighter, Armor Dance,
//     Improved Armor Dance.
//   * Bracketed designators with no union value ([Blood],
//     [Ancestor], [Action]) ship as "general" with the designator
//     carried at the head of the benefit summary (the issue-311
//     bloodline-feat convention). Designators never enter feat names
//     (the ECS Action Boost precedent).
//
// Collisions (see MANIFEST.md): Blooded (Greyhawk) is suffixed -315
// because the id is held by an unrelated weapon special ability;
// Saddleback, Survivor, Mind Over Body, and Animal Affinity are
// suffixed -315 because different feats already hold those ids;
// Piercing Spell is suffixed -315 (a different metamagic feat from
// High Favor: Elves holds the id); Fear is suffixed -315 (the SRD
// spell holds the id); Action Boost is suffixed -315 (the Eberron
// Campaign Setting version, a different feat, holds the id); the
// Kara-Tur Mercantile Background is suffixed -315 because the
// Greyhawk feat of the same name in this same issue takes the base
// id (both are different feats from the FRCS original, which is not
