//   * Eberron preview (p. 106): Action Boost, Lucky Mascot.
//   * Greyhawk (pp. 50–55): the thirty-eight regional feats.
//   * Kara-Tur (pp. 60–67): twenty ancestor feats and five martial
//     arts mastery feats. REMOVED 2026-11-09 at Shaun's order (all
//     oriental material out of the catalog); the records are
